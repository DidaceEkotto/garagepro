export function useI18n() {
    const page = usePage();
    const locale = computed(() => page.props.locale || 'fr');
    const supportedLocales = computed(() => page.props.supportedLocales || []);
    const dir = computed(() => (locale.value === 'ar' ? 'rtl' : 'ltr'));

    watchEffect(() => {
        if (typeof document !== 'undefined') {
            document.documentElement.lang = locale.value;
            document.documentElement.dir = dir.value;
        }
    });

    function t(key, params = {}) {
        const parts = key.split('.');
        const lang = locale.value;
        const merged = {
            ...(messages[lang] || messages.fr),
            ...(extraMessages[lang] || extraMessages.fr),
        };
        let current = merged;
        for (const part of parts) {
            if (current && Object.prototype.hasOwnProperty.call(current, part)) {
                current = current[part];
            } else {
                current = null;
                break;
            }
        }
        if (current === null) {
            const fallbackRoot = { ...messages.fr, ...extraMessages.fr };
            let fallback = fallbackRoot;
            for (const part of parts) {
                fallback = fallback?.[part];
            }
            current = fallback ?? key;
        }
        if (typeof current === 'string') {
            return Object.entries(params).reduce(
                (str, [k, v]) => str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
                current
            );
        }
        return current;
    }

    return { locale, supportedLocales, dir, t };
}
